float Gyro_Calibration(void)
{
    float sum = 0.0f;
    float gyro_value = 0.0f;

    uint32_t valid_samples = 0;

    while (valid_samples < CALIBRATION_SAMPLES)
    {
        if (MPU6050_Read_Gyro_Z(&gyro_value) == HAL_OK)
        {
            sum += gyro_value;
            valid_samples++;
        }

        HAL_Delay(10);
    }
		
    return sum / CALIBRATION_SAMPLES;
}

void Gimbal_Control(float yaw)
{
    float servo_angle = yaw;

    if (servo_angle > 80.0f)
        servo_angle = 80.0f;

    if (servo_angle < -80.0f)
        servo_angle = -80.0f;

    Servo_SetAngle(&camera_servo, 90.0f + servo_angle);
}
